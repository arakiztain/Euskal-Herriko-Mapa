import { DataTypes } from 'sequelize';
import sequelize from '../config/db.js';

const Municipality = sequelize.define('Municipality', {
  id: {
    type: DataTypes.INTEGER,
    primaryKey: true,
    autoIncrement: true
  },
  name: {
    type: DataTypes.STRING,
    allowNull: false
  },
  userId: {
    type: DataTypes.INTEGER,
    allowNull: false,
    references: {
      model: 'User',
      key: 'id'
    }
  }
}, {
  timestamps: true
});

export default Municipality;